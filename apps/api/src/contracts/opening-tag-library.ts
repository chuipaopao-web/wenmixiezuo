export type OpeningTagLane = 'main' | 'auxiliary' | 'trait';

export interface OpeningTagGroup {
  key: string;
  name: string;
  description: string;
  packKeys: string[];
  mainTags: string[];
  auxiliaryTags: string[];
  storyTraits: string[];
}

function group(
  key: string,
  name: string,
  description: string,
  packKeys: string[],
  mainTags: string[],
  auxiliaryTags: string[],
  storyTraits: string[]
): OpeningTagGroup {
  return { key, name, description, packKeys, mainTags, auxiliaryTags, storyTraits };
}

