export function uniqueTagValues(groups: OpeningTagGroup[], lane: OpeningTagLane): string[] {
  const field = lane === 'main' ? 'mainTags' : lane === 'auxiliary' ? 'auxiliaryTags' : 'storyTraits';
  return [...new Set(groups.flatMap((item) => item[field]))];
}
