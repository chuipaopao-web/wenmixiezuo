export function parseVisualTags(value: string): string[] {
  return [...new Set(value.split(/[、,，;；。\n\r]+/u).map((item) => item.trim()).filter(Boolean))];
}

export function serializeVisualTags(value: string[]): string {
  return [...new Set(value.map((item) => item.trim()).filter(Boolean))].join('、');
}
